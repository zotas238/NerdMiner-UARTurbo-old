//Software SHA-256d for the turbo SW miner: nerdSHA256plus' baked double SHA with more
//of the per-job work moved into the bake (see sha256_sw.cpp)
#pragma once
#include <stdint.h>

#define TURBO_SW_BAKE_WORDS 32

//Once per job: mid is the software midstate of header bytes 0..63 (nerd_mids), tail
//points at header bytes 64..79 (the nonce word is not read)
void turbo_sw_bake(const uint32_t *mid, const uint8_t *tail, uint32_t *bake);

//Per nonce (as stored in the header, little endian). True when the hash passes the
//16-bit check (its last two bytes are zero); only then is hash written.
typedef bool (*TurboSwFn)(const uint32_t *bake, uint32_t nonce, uint8_t *hash);
struct TurboSwVariant
{
  const char *name;
  TurboSwFn fn;
};
#ifdef ESP_PLATFORM
#define TURBO_SW_VARIANTS 4   //o2, o2ns, os, asm (sha256_sw_asm.S, generated by gen_sw_asm.py)
#else
#define TURBO_SW_VARIANTS 3
#endif
extern const TurboSwVariant turbo_sw_variants[TURBO_SW_VARIANTS];
extern TurboSwFn turbo_sw_hash;   //the variant in use

//Known-answer test of one variant
bool turbo_sw_selftest(TurboSwFn fn);
//ESP only: H7 of the assembly version vs the reference (0 = all agree, else 1 + index)
uint32_t turbo_sw_asm_check(uint32_t count, uint32_t *got, uint32_t *want);

//Independent reference double SHA of an 80-byte header with the given nonce, for
//checking candidates before they are submitted
void turbo_ref_sha256d(const uint8_t *hdr, uint32_t nonce, uint8_t *hash);
bool turbo_ref_check(const uint8_t *hdr, uint32_t nonce, const uint8_t *hash);
